"""Rebuild wiki/index.md from page frontmatter.

Usage: python3 -I scripts/build_index.py
Speaker lines are generated from frontmatter (key metrics); other pages use their `summary`/`title`
frontmatter or first heading. Static descriptions for concepts/reviewers live in DESCRIPTIONS below.
"""
import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
WIKI = ROOT / "wiki"

BANDS = [(0, 300, "< $300 / pair"), (300, 600, "$300–600 / pair"), (600, 1200, "$600–1,200 / pair"),
         (1200, 2500, "$1,200–2,500 / pair"), (2500, 10 ** 9, "> $2,500 / pair")]

DESCRIPTIONS = {
    "spinorama": "the CTA-2034-A curve set and how this wiki computes metrics from it",
    "listening-window": "LW definition and the ±dB deviation metric (300 Hz–10 kHz, 1/6 oct)",
    "early-reflections": "ER construction and the 1–5 kHz dip check",
    "sound-power": "SP weighting and interpretation",
    "directivity-index": "SPDI/ERDI, beamwidth, DI smoothness grading, toe-in from data",
    "preference-score": "Olive model, with and without sub; limits",
    "sensitivity-normalization": "dB @ 2.83 V / 1 m; converting per-watt specs",
    "impedance-and-epdr": "IEC 80% rule, flags, EPDR, amplifier guidance",
    "compression-and-max-spl": "compression, max SPL, THD conventions",
    "bass-extension-vs-room-gain": "f3/f6 definitions; room gain is not credited",
    "active-alternatives": "powered models encountered (out of scope)",
    "asr": "Audio Science Review: Klippel NFS, Tier A",
    "erins-audio-corner": "Erin's Audio Corner: Klippel NFS plus compression tests, Tier A",
    "audioholics": "Audioholics: ground-plane/gated polars, Tier A with spinorama",
    "soundstage-nrc": "SoundStage! via NRC anechoic chamber, Tier A",
    "stereophile": "Stereophile: gated quasi-anechoic with EPDR commentary, Tier B",
    "princeton-3d3a": "Princeton 3D3A anechoic directivity database (2015), Tier A",
}


def fm(path):
    t = path.read_text()
    if t.startswith("---"):
        try:
            return yaml.safe_load(t.split("---", 2)[1]) or {}, t
        except Exception:  # noqa: BLE001
            return {}, t
    return {}, t


def heading(text):
    m = re.search(r"^# (.+)$", text, re.M)
    return m.group(1).strip() if m else ""


def fmt(v, unit="", dec=None):
    if v is None:
        return None
    if dec is not None:
        v = f"{float(v):.{dec}f}"
    return f"{v}{unit}"


def speaker_line(f):
    bits = []
    if f.get("nominal_impedance_ohm"):
        bits.append(f"{f['nominal_impedance_ohm']} Ω")
    if f.get("lw_deviation_db") is not None:
        bits.append(f"LW ±{float(f['lw_deviation_db']):.1f} dB")
    if f.get("f3_hz"):
        bits.append(f"f3 {f['f3_hz']} Hz")
    if f.get("sensitivity_db_2v83"):
        bits.append(f"{float(f['sensitivity_db_2v83']):.1f} dB/2.83 V")
    if f.get("pref_score") is not None:
        s = f"pref {f['pref_score']}"
        if f.get("pref_score_sub") is not None:
            s += f"/{f['pref_score_sub']} w/sub"
        bits.append(s)
    if f.get("impedance_flag"):
        bits.append(f"⚑ {f['impedance_flag']}")
    if f.get("price_usd_pair"):
        bits.append(f"${int(round(float(f['price_usd_pair']))):,}/pr")
    return f"- [[{f['slug']}]] — {f.get('brand')} {f.get('model')}: " + ", ".join(bits)


def main():
    out = ["# Index", "", "Catalog of every wiki page. Regenerated by `scripts/build_index.py`; do not hand-edit.", "",
           "## Overview", "- [[overview]] — current state of the research: shortlist, open questions, thesis", ""]

    speakers = []
    for p in sorted((WIKI / "speakers").glob("*.md")):
        f, _ = fm(p)
        if f.get("type") == "speaker":
            speakers.append(f)
    out.append(f"## Speakers ({len(speakers)})")
    out.append("Key: nominal impedance, listening-window deviation, anechoic f3, sensitivity, Olive preference score "
               "(no sub/with sub), impedance flag, street price per pair. Discontinued models are listed separately.")
    cur = [s for s in speakers if s.get("status") != "discontinued"]
    for lo, hi, label in BANDS:
        rows = [s for s in cur if s.get("price_usd_pair") is not None and lo <= float(s["price_usd_pair"]) < hi]
        out += ["", f"### {label} ({len(rows)})"]
        out += [speaker_line(s) for s in sorted(rows, key=lambda s: float(s["price_usd_pair"]))]
    nop = [s for s in cur if s.get("price_usd_pair") is None]
    if nop:
        out += ["", f"### Price unknown ({len(nop)})"] + [speaker_line(s) for s in nop]
    disc = [s for s in speakers if s.get("status") == "discontinued"]
    if disc:
        out += ["", f"### Discontinued (reference only, {len(disc)})"] + [speaker_line(s) for s in disc]
    out.append("")

    def section(title, folder, desc_fn):
        pages = sorted((WIKI / folder).glob("*.md"))
        out.append(f"## {title} ({len(pages)})")
        for p in pages:
            f, t = fm(p)
            out.append(f"- [[{p.stem}]] — {desc_fn(p.stem, f, t)}")
        out.append("")

    section("Brands", "brands", lambda s, f, t: f.get("summary") or heading(t))
    section("Comparisons", "comparisons", lambda s, f, t: f.get("summary") or heading(t))
    section("Concepts", "concepts", lambda s, f, t: DESCRIPTIONS.get(s) or heading(t))
    section("Reviewers", "reviewers", lambda s, f, t: DESCRIPTIONS.get(s) or heading(t))

    def src_desc(s, f, t):
        parts = [str(f.get("outlet") or f.get("author") or "").strip(), str(f.get("title") or heading(t)).strip()]
        d = " — ".join(x for x in parts if x)
        if f.get("published"):
            d += f", {f['published']}"
        if f.get("tier"):
            d += f" (Tier {str(f['tier'])[:1]})"
        return d

    section("Sources", "sources", src_desc)
    (WIKI / "index.md").write_text("\n".join(out).rstrip() + "\n")
    print(f"index: {len(speakers)} speakers")


if __name__ == "__main__":
    main()
