"""Size / weight comparison from data/speakers.csv -> wiki/comparisons/size-and-weight.md (Notes section preserved).

Usage: python3 -I scripts/size_table.py
Dimensions are manufacturer specs (Tier C), per speaker, H x W x D in mm; some include grilles, tweeter pods or plinths.
"""
import csv
import math
import re
import statistics as st
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def f(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return None


def main():
    rows = []
    for r in csv.DictReader(open(ROOT / "data" / "speakers.csv")):
        nums = [float(x) for x in re.findall(r"\d+(?:\.\d+)?", r["dimensions_mm"] or "")]
        if len(nums) < 3 or r["status"] != "current" or r.get("category") == "on-wall":
            continue
        h, w, d = nums[:3]
        rows.append(dict(slug=r["slug"], h=h, w=w, d=d, L=h * w * d / 1e6, kg=f(r["weight_kg"]), f3=f(r["f3_hz"]),
                         psub=f(r["pref_score_sub"]), price=f(r["price_usd_pair"]), woofer=f(r["woofer_in"])))
    rows.sort(key=lambda r: r["L"])
    pairs = [(math.log(r["L"]), math.log(r["f3"])) for r in rows if r["f3"]]
    xs, ys = zip(*pairs)
    mx, my = st.mean(xs), st.mean(ys)
    slope = sum((x - mx) * (y - my) for x, y in pairs) / sum((x - mx) ** 2 for x in xs)
    rcorr = st.correlation(xs, ys)
    for r in rows:
        r["f3_resid"] = (math.log(r["f3"]) - (my + slope * (math.log(r["L"]) - mx))) if r["f3"] else None

    def q(k):
        v = sorted(r[k] for r in rows if r[k] is not None)
        return v[0], st.median(v), v[-1]

    def d(v, dec=0):
        return "—" if v is None else f"{v:.{dec}f}"

    lines = ["| Speaker | H×W×D mm | Volume L | kg (each) | Woofer in | f3 Hz | f3 vs size | Pref w/sub | $/pr |", "|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        res = "" if r["f3_resid"] is None else (f"{100 * (math.exp(r['f3_resid']) - 1):+.0f}%")
        lines.append(f"| [[{r['slug']}]] | {r['h']:.0f}×{r['w']:.0f}×{r['d']:.0f} | {r['L']:.1f} | {d(r['kg'], 1)} | {d(r['woofer'], 2) if r['woofer'] else '—'} | "
                     f"{d(r['f3'])} | {res} | {d(r['psub'], 1)} | {d(r['price'])} |")
    s = {k: q(k) for k in ("h", "w", "d", "L", "kg")}
    intro = (f"Manufacturer-stated cabinet sizes (Tier C) for {len(rows)} current speakers, smallest to largest by volume. "
             f"**Height** {s['h'][0]:.0f}–{s['h'][2]:.0f} mm (median {s['h'][1]:.0f}); **width** {s['w'][0]:.0f}–{s['w'][2]:.0f} mm (median {s['w'][1]:.0f}); "
             f"**depth** {s['d'][0]:.0f}–{s['d'][2]:.0f} mm (median {s['d'][1]:.0f}); **gross volume** {s['L'][0]:.1f}–{s['L'][2]:.1f} L (median {s['L'][1]:.1f}); "
             f"**weight** {s['kg'][0]:.1f}–{s['kg'][2]:.1f} kg each (median {s['kg'][1]:.1f}).\n\n"
             f"\"f3 vs size\" is each speaker's anechoic f3 relative to a power-law fit of f3 against box volume (log–log, n={len(pairs)}, "
             f"slope {slope:.2f}, r = {rcorr:.2f}). Negative means deeper bass than its size predicts. The fit is loose, because tuning, "
             f"port vs sealed design and the f3 definition matter as much as volume ([[bass-extension-vs-room-gain]]). Volume is external "
             f"H×W×D, not internal air volume. Generated by `scripts/size_table.py`.")
    path = ROOT / "wiki" / "comparisons" / "size-and-weight.md"
    notes = "## Notes\n_(none yet)_\n"
    if path.exists() and "## Notes" in path.read_text():
        t = path.read_text()
        notes = t[t.index("## Notes"):].split("\n## Related")[0].rstrip() + "\n"
    path.write_text("\n".join(["---", "type: comparison", "slug: size-and-weight",
                               f"summary: Cabinet sizes {s['L'][0]:.0f}–{s['L'][2]:.0f} L (median {s['L'][1]:.0f} L); bass extension vs box size",
                               "generated_by: scripts/size_table.py", "last_updated: 2026-10-11", "---", "# Size and weight", "", intro, "",
                               "\n".join(lines), "", notes, "## Related",
                               "[[ranked-by-price-band]] · [[bass-extension-vs-room-gain]] · [[overview]]", ""]))
    print(f"n={len(rows)} slope={slope:.2f} r={rcorr:.2f}")
    for r in sorted([r for r in rows if r["f3_resid"] is not None], key=lambda r: r["f3_resid"])[:6]:
        print("deep-for-size", r["slug"], round(r["L"], 1), r["f3"], f"{100*(math.exp(r['f3_resid'])-1):+.0f}%")
    for r in sorted([r for r in rows if r["f3_resid"] is not None], key=lambda r: -r["f3_resid"])[:6]:
        print("shallow-for-size", r["slug"], round(r["L"], 1), r["f3"], f"{100*(math.exp(r['f3_resid'])-1):+.0f}%")
    dens = sorted([r for r in rows if r["kg"]], key=lambda r: -r["kg"] / r["L"])
    print("densest", [(r["slug"], round(r["kg"] / r["L"], 2)) for r in dens[:4]], "lightest", [(r["slug"], round(r["kg"] / r["L"], 2)) for r in dens[-3:]])
    small_good = sorted([r for r in rows if r["psub"] and r["L"] < 15], key=lambda r: -r["psub"])[:6]
    print("best psub under 15 L", [(r["slug"], round(r["L"], 1), r["psub"]) for r in small_good])


if __name__ == "__main__":
    main()
    import sys as _s
    _s.path.insert(0, str(Path(__file__).resolve().parent))
    import wikilinks_to_md
    wikilinks_to_md.main()
